"""Runs on GitHub Ubuntu after flutter create, ensures Android Bluetooth permissions.
This is intentionally idempotent. Do not change Android package name/signing here.
"""
from pathlib import Path
import re

manifest = Path('android/app/src/main/AndroidManifest.xml')
if not manifest.exists():
    raise SystemExit('AndroidManifest.xml not found; flutter create failed')
content = manifest.read_text()
needed = [
    '<uses-permission android:name="android.permission.BLUETOOTH" android:maxSdkVersion="30" />',
    '<uses-permission android:name="android.permission.BLUETOOTH_ADMIN" android:maxSdkVersion="30" />',
    '<uses-permission android:name="android.permission.BLUETOOTH_CONNECT" />',
]
match = re.search(r'<manifest\b[^>]*>', content)
if not match:
    raise SystemExit('Invalid AndroidManifest.xml: no manifest tag')
missing = [entry for entry in needed if entry.split('android:name="')[1].split('"')[0] not in content]
if missing:
    content = content[:match.end()] + '\n    ' + '\n    '.join(missing) + content[match.end():]
content = content.replace('android:label="agan_ponsel"', 'android:label="AGAN PONSEL"')
manifest.write_text(content)

generated_test = Path('test/widget_test.dart')
if generated_test.exists():
    text = generated_test.read_text()
    if 'class MyApp' in text or 'await tester.pumpWidget(const MyApp())' in text or 'Counter increments smoke test' in text:
        generated_test.unlink()
        print('Removed incompatible autogenerated Flutter counter widget test')
print('Android Bluetooth Classic manifest configured; Flutter source unchanged')
